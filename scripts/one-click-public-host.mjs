import { spawn, spawnSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import { platform } from 'node:os';
import { setTimeout as delay } from 'node:timers/promises';

const isWindows = platform() === 'win32';
const npmCmd = isWindows ? 'npm.cmd' : 'npm';

let tunnelProcess;
let appProcess;
let stopping = false;

main().catch((error) => {
  console.error('\n[one-click] Fatal error:', error.message);
  shutdown(1);
});

async function main() {
  console.log('[one-click] Starting public host launcher...');

  ensureCloudflared();
  await ensureDependencies();

  const publicUrl = await startTunnelAndCaptureUrl();
  console.log(`[one-click] Public URL detected: ${publicUrl}`);
  console.log('[one-click] Launching app with PUBLIC_BASE_URL preconfigured...');

  startApp(publicUrl);
  attachSignalHandlers();

  console.log('\n[one-click] Hosting is live.');
  console.log(`[one-click] Share links generated by the app (using ${publicUrl}).`);
  console.log('[one-click] Press Ctrl+C to stop both app and tunnel.\n');
}

function ensureCloudflared() {
  const result = spawnSync('cloudflared', ['--version'], {
    stdio: 'pipe',
    encoding: 'utf8',
  });

  if (result.status === 0) {
    const version = String(result.stdout || result.stderr || '').trim();
    console.log(`[one-click] cloudflared found: ${version}`);
    return;
  }

  console.error('[one-click] cloudflared is not installed or not available in PATH.');

  if (isWindows) {
    console.error('[one-click] Install with: winget install --id Cloudflare.cloudflared');
  } else {
    console.error('[one-click] Install cloudflared from Cloudflare docs, then re-run this launcher.');
  }

  process.exit(1);
}

async function ensureDependencies() {
  if (existsSync('node_modules')) {
    console.log('[one-click] node_modules found. Skipping install.');
    return;
  }

  console.log('[one-click] node_modules missing. Running npm install (first run)...');
  await runNpm(['install']);
}

function runNpm(args) {
  return new Promise((resolve, reject) => {
    const child = spawn(npmCmd, args, {
      stdio: 'inherit',
      shell: false,
    });

    child.on('error', reject);
    child.on('exit', (code) => {
      if (code === 0) {
        resolve();
        return;
      }

      reject(new Error(`npm ${args.join(' ')} failed with exit code ${code}`));
    });
  });
}

async function startTunnelAndCaptureUrl() {
  return new Promise((resolve, reject) => {
    let settled = false;
    let outputBuffer = '';

    tunnelProcess = spawn('cloudflared', ['tunnel', '--url', 'http://localhost:3001'], {
      stdio: ['ignore', 'pipe', 'pipe'],
      shell: false,
    });

    const onData = (chunk) => {
      const text = chunk.toString();
      outputBuffer += text;
      process.stdout.write(`[tunnel] ${text}`);

      const match = outputBuffer.match(/https:\/\/[a-zA-Z0-9.-]+\.trycloudflare\.com/);
      if (!settled && match?.[0]) {
        settled = true;
        resolve(match[0]);
      }
    };

    tunnelProcess.stdout.on('data', onData);
    tunnelProcess.stderr.on('data', onData);

    tunnelProcess.on('error', (error) => {
      if (!settled) {
        settled = true;
        reject(error);
      }
    });

    tunnelProcess.on('exit', (code) => {
      if (!settled) {
        settled = true;
        reject(new Error(`cloudflared exited before URL capture (code ${code ?? 'unknown'})`));
      } else if (!stopping) {
        console.error(`\n[one-click] Tunnel exited unexpectedly (code ${code ?? 'unknown'}).`);
        shutdown(1);
      }
    });

    void (async () => {
      await delay(25000);
      if (!settled) {
        settled = true;
        reject(new Error('Timed out waiting for trycloudflare URL.'));
      }
    })();
  });
}

function startApp(publicUrl) {
  const env = {
    ...process.env,
    PUBLIC_BASE_URL: publicUrl,
  };

  appProcess = spawn(npmCmd, ['run', 'start'], {
    stdio: 'inherit',
    shell: false,
    env,
  });

  appProcess.on('error', (error) => {
    console.error('\n[one-click] App process failed:', error.message);
    shutdown(1);
  });

  appProcess.on('exit', (code) => {
    if (!stopping) {
      console.error(`\n[one-click] App exited (code ${code ?? 'unknown'}). Stopping tunnel...`);
      shutdown(code ?? 1);
    }
  });
}

function attachSignalHandlers() {
  process.on('SIGINT', () => shutdown(0));
  process.on('SIGTERM', () => shutdown(0));
}

function shutdown(exitCode) {
  if (stopping) {
    return;
  }

  stopping = true;

  if (appProcess && !appProcess.killed) {
    appProcess.kill('SIGTERM');
  }

  if (tunnelProcess && !tunnelProcess.killed) {
    tunnelProcess.kill('SIGTERM');
  }

  setTimeout(() => process.exit(exitCode), 300);
}
